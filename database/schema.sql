-- ---------------------------------------------------------------------------
-- 1. Expenses
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS expenses (
    -- Random UUID generated by PostgreSQL. UUIDs avoid exposing sequential
    -- record counts and make records safe to reference in URLs.
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- NUMERIC (not FLOAT) keeps money exact. The check rejects zero,
    -- negative, and therefore invalid amounts at the database level.
    amount NUMERIC(12,2) NOT NULL
        CHECK (amount > 0),

    -- The database only accepts the five categories used by the UI.
    category VARCHAR(30) NOT NULL
        CHECK (
            category IN (
                'Food',
                'Travel',
                'Shopping',
                'Bills',
                'Other'
            )
        ),

    -- Optional free-text note. Empty descriptions are stored as NULL.
    description TEXT,

    -- Calendar date of the expense (no time or timezone component).
    expense_date DATE NOT NULL,

    -- Audit timestamp, set automatically when the row is inserted.
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Where the record came from: manual UI entry or automated ingestion.
    source VARCHAR(30) NOT NULL DEFAULT 'manual',

    -- Stable identifier from the source file. Used for deduplication.
    external_id VARCHAR(255),

    -- Optional link to the automation run that imported the record.
    import_run_id UUID
);

-- ---------------------------------------------------------------------------
-- 2. Admin users (authentication + role-based access control)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    email VARCHAR(255) NOT NULL,

    -- bcrypt hash. Plain-text passwords are never stored.
    password_hash TEXT NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'viewer'
        CHECK (role IN ('admin', 'viewer')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ
);

-- Case-insensitive unique email addresses.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
    ON users (LOWER(email));

-- ---------------------------------------------------------------------------
-- 3. Automation import runs
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS import_runs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    source VARCHAR(30) NOT NULL DEFAULT 'automation',
    file_name TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'completed', 'failed')),

    imported_count INTEGER NOT NULL DEFAULT 0,
    skipped_count INTEGER NOT NULL DEFAULT 0,
    failed_count INTEGER NOT NULL DEFAULT 0,
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,

    error_message TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ
);

-- ---------------------------------------------------------------------------
-- 4. Add new expense columns to databases created before automation existed
-- ---------------------------------------------------------------------------

ALTER TABLE expenses
    ADD COLUMN IF NOT EXISTS source VARCHAR(30) NOT NULL DEFAULT 'manual';

ALTER TABLE expenses
    ADD COLUMN IF NOT EXISTS external_id VARCHAR(255);

ALTER TABLE expenses
    ADD COLUMN IF NOT EXISTS import_run_id UUID;

-- Add the foreign key separately so this migration works on old databases.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'expenses_import_run_id_fkey'
    ) THEN
        ALTER TABLE expenses
            ADD CONSTRAINT expenses_import_run_id_fkey
            FOREIGN KEY (import_run_id)
            REFERENCES import_runs (id)
            ON DELETE SET NULL;
    END IF;
END
$$;

-- ---------------------------------------------------------------------------
-- 5. Indexes
-- ---------------------------------------------------------------------------

-- Supports the default "newest expense date first" ordering, with
-- created_at as a deterministic tie-breaker for same-day expenses.
CREATE INDEX IF NOT EXISTS idx_expenses_date
    ON expenses (expense_date DESC, created_at DESC);

-- Supports the optional category filter without scanning the whole table.
CREATE INDEX IF NOT EXISTS idx_expenses_category
    ON expenses (category);

-- Supports source breakdowns and automation filtering.
CREATE INDEX IF NOT EXISTS idx_expenses_source
    ON expenses (source);

-- Prevents the same imported transaction from being inserted twice.
CREATE UNIQUE INDEX IF NOT EXISTS idx_expenses_source_external
    ON expenses (source, external_id)
    WHERE external_id IS NOT NULL;

-- Supports the admin "recent imports" panel.
CREATE INDEX IF NOT EXISTS idx_import_runs_started
    ON import_runs (started_at DESC);

